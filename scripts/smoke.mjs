function runDsh(task, overlayPath, home, workspaceDir) {
  return new Promise((resolvePromise) => {
    const args = [
      DSH_BIN,
      "--profile",
      "headless",
      "--patch",
      REPO_PATCH,
      "--patch",
      overlayPath,
      task,
    ];
    const child = spawn(process.execPath, args, {
      cwd: workspaceDir,
      env: {
        ...process.env,
        DSH_HOME: home,
        DSH_PERMISSION_MODE: "danger-full-access",
        DSH_TELEMETRY_DISABLED: "1",
      },
      stdio: ["ignore", "pipe", "pipe"],
    });
    let stdout = "";
    let stderr = "";
    child.stdout.on("data", (chunk) => {
      stdout += String(chunk);
    });
    child.stderr.on("data", (chunk) => {
      stderr += String(chunk);
    });
    const killTimer = setTimeout(() => child.kill("SIGTERM"), 240_000);
    child.on("exit", (code, signal) => {
      clearTimeout(killTimer);
      writeFileSync(join(TMP_ROOT, "dsh-stdout.txt"), stdout);
      writeFileSync(join(TMP_ROOT, "dsh-stderr.txt"), stderr);
      resolvePromise({ code: code ?? -1, signal, stdout, stderr });
    });
  });
}

/** 最新落盘的 session jsonl（compression:none → `session.v4.jsonl`）。 */
function findSessionLog(home) {
  const sessionsRoot = join(home, "sessions");
  const found = [];
  const visit = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) visit(path);
      else if (entry.isFile() && entry.name.endsWith(".jsonl")) {
        found.push({ path, mtime: statSync(path).mtimeMs });
      }
    }
  };
  if (existsSync(sessionsRoot)) visit(sessionsRoot);
  found.sort((left, right) => right.mtime - left.mtime);
  return found[0]?.path;
}

function runReplay(logPath) {
  // 日志路径 <root>/<encoded-cwd>/<session-id>/session.v4.jsonl。
  const sessionId = basename(dirname(logPath));
  const root = dirname(dirname(dirname(logPath)));  const child = spawn(process.execPath, [join(TMP_ROOT, "replay.mjs"), root, sessionId], {
    stdio: ["ignore", "pipe", "pipe"],
  });
  let stdout = "";
  let stderr = "";
  child.stdout.on("data", (chunk) => {
    stdout += String(chunk);
  });
  child.stderr.on("data", (chunk) => {
    stderr += String(chunk);
  });
  return new Promise((resolvePromise, rejectPromise) => {
    child.on("error", rejectPromise);
    child.on("exit", (code) => {
      if (code !== 0) {
        rejectPromise(new Error(`replay child exited ${String(code)}: ${stderr.slice(-2000)}`));
        return;
      }
      try {
        resolvePromise(JSON.parse(stdout));
      } catch (error) {
        rejectPromise(new Error(`replay child printed unparsable output: ${String(error)}\n${stdout.slice(0, 500)}`));
      }
    });
  });
}

