async function main() {
  const realModel = process.argv.includes("--real-model");
  if (realModel && process.env.DEEPSEEK_API_KEY === undefined) {
    console.error("[smoke] FAIL: --real-model 需要 DEEPSEEK_API_KEY 环境变量");
    process.exit(1);
  }

  // ---- 0. 前置：插件构建产物在场 ----
  const distEntry = join(REPO_ROOT, "dist", "src", "index.js");
  if (!existsSync(distEntry)) {
    console.error("[smoke] FAIL: dist/src/index.js 不存在 —— 先跑 `pnpm build`");
    process.exit(1);
  }

  // ---- 1. 隔离环境（每次全新）----
  rmSync(TMP_ROOT, { recursive: true, force: true });
  mkdirSync(TMP_ROOT, { recursive: true });
  const home = join(TMP_ROOT, "home");
  const workspaceDir = join(TMP_ROOT, "workspace");
  mkdirSync(home, { recursive: true });
  mkdirSync(workspaceDir, { recursive: true });
  log(`DSH_HOME=${home}`);

  // ---- 2. 打包插件（插件产物 + 驱动；@deepseek-ai/* external）----
  const driverSource = join(TMP_ROOT, "smoke-driver.js");
  writeFileSync(driverSource, DRIVER_SOURCE);
  const bundleDir = join(TMP_ROOT, "bundle");
  mkdirSync(bundleDir, { recursive: true });
  runEsbuildBundle(distEntry, driverSource, bundleDir);
  log("plugin bundle built (esbuild, @deepseek-ai/* external)");

  // ---- 3. profile + 插件包物化 + patch 层 ----
  const profileDir = initHeadlessProfile(home);
  materializePluginPackage(profileDir, bundleDir);
  const overlayPath = writeSmokeOverlay(home, realModel);
  log(`profile prepared at ${profileDir}`);

  // ---- 4. 真实 dsh 进程：headless one-shot（注入 prompt → 等待 turn 完成）----
  log(`spawning real dsh: dsh --profile headless --patch <repo cordis.patch.yml> --patch <smoke overlay> "<task>"`);
  const { code, stdout, stderr } = await runDsh(TASK, overlayPath, home, workspaceDir);
  log(`dsh exited with code ${String(code)}`);
  if (code !== 0) {
    console.error(stderr.slice(-4000));
  }

  // ---- AC1：0 退出、turn 完成、stdout 终答 ----
  assert(code === 0, `real dsh headless run must exit 0, got ${String(code)}\nstderr tail:\n${stderr.slice(-2000)}`);
  assert(
    stdout.trim() === FINAL_TEXT,
    `headless stdout (final assistant text) must be ${JSON.stringify(FINAL_TEXT)}, got ${JSON.stringify(stdout.trim())}`,
  );
  log(`AC1 turn completed: stdout=${JSON.stringify(stdout.trim())}`);

  // ---- AC1：进程内驱动痕迹（fake 模型 2 次调用、工具经 dsh 管线执行）----
  const tracePath = join(home, "smoke-driver-trace.json");
  assert(existsSync(tracePath), `driver trace file must exist at ${tracePath}`);
  const trace = JSON.parse(readFileSync(tracePath, "utf8"));
  assert(trace.profileName === "headless", `driver must run in the real headless profile, got ${JSON.stringify(trace.profileName)}`);
  assert(trace.adapterCalls === 2, `fake adapter must serve exactly 2 model calls, got ${String(trace.adapterCalls)}`);
  assert(
    Array.isArray(trace.requestTools[0]) && trace.requestTools[0].includes(ECHO_TOOL),
    `first model request must carry the bridged dsh tool surface including ${ECHO_TOOL}, got ${JSON.stringify(trace.requestTools[0]?.slice(0, 40))}`,
  );
  assert(trace.toolExecutions.length === 1, `echo tool must execute exactly once, got ${JSON.stringify(trace.toolExecutions)}`);
  assert(
    trace.toolExecutions[0]?.args?.text === "smoke",
    `echo tool arguments must be {text:"smoke"}, got ${JSON.stringify(trace.toolExecutions[0]?.args)}`,
  );
  assert(trace.preExecute >= 1, `tools/pre-execute must fire (dsh pipeline, not bypass), got ${String(trace.preExecute)}`);
  log(
    `AC1 pipeline probes: adapterCalls=${String(trace.adapterCalls)}, toolExecutions=${String(trace.toolExecutions.length)}, preExecute=${String(trace.preExecute)}, toolsInRequest=${String(trace.requestTools[0]?.length)}`,
  );

  // ---- AC1：$DSH_HOME/sessions/…jsonl 存在且事件序列合法、工具痕迹在 log 中 ----
  const logPath = findSessionLog(home);
  assert(logPath !== undefined, `session jsonl must exist under ${join(home, "sessions")}`);
  const rawLog = readFileSync(logPath, "utf8");
  const rawLines = rawLog.split("\n").filter((line) => line.length > 0);
  assert(rawLines.length >= 2, `session log must hold a header line plus events, got ${String(rawLines.length)} lines at ${logPath}`);
  for (const needle of ["turn/start", "user/message", "assistant/message", "tool/call", "tool/result", "turn/end", "agent/inbox/spliced"]) {
    assert(
      rawLog.includes(`"${needle}"`),
      `session log must contain a "${needle}" event (tool execution trace must reach the durable log)`,
    );
  }
  assert((rawLog.match(/"turn\/start"/g) ?? []).length >= 1, "log must contain turn/start");
  log(`AC1 session log ok: ${logPath} (${String(rawLines.length - 1)} events, plaintext jsonl)`);

  // ---- AC2：deriveMessages() 对该 log 重放成功（独立子进程，npm 后端读回）----
  writeFileSync(join(TMP_ROOT, "replay.mjs"), REPLAY_SOURCE);
  const replay = await runReplay(logPath);
  log(`AC2 replay: ${String(replay.eventCount)} events -> ${replay.roles.join(" -> ")}`);
  // log 里除 zcode-loop 的 turn 骨架外还有真实 dsh 各行的生命周期事件
  // （permission/preset、sandbox/mode、approval/policy、session/title 等）——
  // turn 骨架断言取首个 turn/start 到末个 turn/end 的窗口。
  const allTypes = replay.types;
  const firstTurnStart = allTypes.indexOf("turn/start");
  const lastTurnEnd = allTypes.lastIndexOf("turn/end");
  assert(firstTurnStart >= 0 && lastTurnEnd > firstTurnStart, `replayed log must hold a turn/start…turn/end window, got ${JSON.stringify(allTypes)}`);
  const types = allTypes.slice(firstTurnStart, lastTurnEnd + 1);
  assert(types.length >= 2, `turn window must hold events, got ${JSON.stringify(types)}`);
  assert(types[0] === "turn/start", `turn window must open with turn/start, got ${types[0]}`);
  assert(types.at(-1) === "turn/end", `turn window must close with turn/end, got ${types.at(-1)}`);
  assert(types.includes("tool/call") && types.includes("tool/result"), "turn window must include tool/call and tool/result");
  assert(replay.roles[0] === "system", `derived messages must open with system, got ${replay.roles[0]}`);
  assert(
    replay.roles.includes("user") && replay.roles.includes("assistant") && replay.roles.includes("tool"),
    `derived messages must rebuild the full backbone, got ${replay.roles.join(" -> ")}`,
  );
  assert(replay.finalText === FINAL_TEXT, `derived final assistant text must match, got ${JSON.stringify(replay.finalText)}`);
  assert(
    replay.systemText.startsWith("You are an AI agent powered by DeepSeek Harness."),
    `derived system message must use the admitted dsh assembly, got ${JSON.stringify(replay.systemText.slice(0, 120))}...`,
  );
  assert(replay.toolCalls.length === 1 && replay.toolCalls[0]?.name === ECHO_TOOL, `derived assistant must carry the ${ECHO_TOOL} call, got ${JSON.stringify(replay.toolCalls)}`);
  assert(replay.toolResults.length === 1, `derived must hold exactly one tool message, got ${JSON.stringify(replay.toolResults)}`);
  assert(
    replay.toolResults[0]?.toolCallId === replay.toolCalls[0]?.id,
    `derived tool message must pair with the assistant tool-call id`,
  );
  assert(replay.toolResults[0]?.isError === false, "derived tool result must not be an error");
  assert(
    replay.toolResults[0]?.text.includes("Tool says: smoke"),
    `derived tool result must carry the dsh-rendered output (pipeline proof), got ${JSON.stringify(replay.toolResults[0]?.text)}`,
  );
  log(`AC2 deriveMessages rebuilt: final=${JSON.stringify(replay.finalText)}, toolResult=${JSON.stringify(replay.toolResults[0]?.text)}`);

  console.log(`[smoke] artifacts kept under ${TMP_ROOT} (session log: ${logPath})`);
  console.log("[smoke] PASS: real-dsh end-to-end smoke green (AC1 + AC2; AC3 web eyeball check is manual/optional)");
}

main().catch((error) => {
  console.error(`[smoke] FAIL: ${error instanceof Error ? (error.stack ?? error.message) : String(error)}`);
  process.exit(1);
});
