#!/usr/bin/env node
/**
 * 真实 dsh 端到端冒烟（集成验收）。
 *
 * 被测对象 = 独立从 npm 拉取的真实 dsh（devDependency `@deepseek-ai/dsh`），
 * 以真实进程/CLI 形态（headless one-shot）跑一条完整对话路径：
 *
 *   脚本注入 prompt（dsh headless "<task>"）
 *   → dsh inbox 接收（本插件 ZcodeLoopInbox）
 *   → ZCode 引擎驱动模型请求（model-bridge → dsh llm 路由 → 本脚本落进去的
 *     fake adapter，脚本化"文本 + 工具调用"→"终答"两步）
 *   → 模型发起工具调用 → 工具经 dsh ToolRuntime 管线执行（本插件以 dsh 工具
 *     插件同款注册面 ctx.tools.register 落的 echo 工具；pre-execute 计数器
 *     证明走的是 dsh 管线而非旁路）
 *   → 结果回填引擎 → 引擎结束 turn → dsh session log 落的是合法 dsh
 *   SessionEvent（$DSH_HOME/sessions/…/session.v4.jsonl）。
 *
 * AC（任务合同）：
 *   1. 本脚本 0 退出：turn 完成、session jsonl 存在且事件序列合法、
 *      工具执行痕迹（tool/result）在 log 中。
 *   2. `deriveMessages()` 对该 log 重放成功（独立重放子进程：npm
 *      session-persistence-jsonl 后端读回事件 → npm dsh-session 重放）。
 *   3. （可选，手动）`dsh web` 肉眼确认回合推进 —— 不在本脚本内断言。
 *
 * 装配（全部真实 dsh 形态，零 dsh 源码修改）：
 *   - profile：`headless`（shipped template = dsh-base + dsh-headless bundle），
 *     `$DSH_HOME` 指向 `.agent-work/tmp/smoke/home`（数据隔离）。
 *   - 环境变量：`DSH_PERMISSION_MODE=danger-full-access`（approval=never，
 *     sandbox=danger-full-access）、`DSH_TELEMETRY_DISABLED=1`。
 *   - profile patch：仓库根的 `cordis.patch.yml`（disable stock `agent-loop` +
 *     insert `zcode-loop`）+ 本脚本生成的 smoke overlay（provider/model 指到
 *     fake adapter；关掉会偷跑 LLM 的 session-title-llm；session-persistence
 *     用 compression:none 落明文 jsonl；insert fake 模型/工具驱动行）。
 *   - 本插件包：以 esbuild 把 `dist/src`（插件）+ 驱动源码各自打成单文件
 *     bundle（`@deepseek-ai/*` 保持 external —— 运行时由 dsh 的 runtime
 *     resolution 统一供给宿主单例），物化为
 *     `<profile>/node_modules/dsh-plugin-zcode-loop/`（`./` 与 `./smoke-driver`
 *     两个入口）。
 *
 * 可选真实模型冒烟：`node scripts/smoke.mjs --real-model`（需 DEEPSEEK_API_KEY，
 * 不阻塞验收；provider/model 换 deepseek-official/deepseek-flash 且不插 fake 行）。
 *
 * 用法：`pnpm build && pnpm verify:smoke`。
 */
