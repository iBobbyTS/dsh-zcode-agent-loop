/** fake 模型 + echo 工具驱动（以 dsh 插件形态在真实 dsh 进程内挂载）。 */
const DRIVER_SOURCE = `// generated by scripts/smoke.mjs — fake llm adapter + echo tool driver
import { LlmAdapter, ToolCallId } from "@deepseek-ai/dsh-llm";
import { defineTool } from "@deepseek-ai/dsh-tools";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const tracePath = join(process.env.DSH_HOME ?? ".", "smoke-driver-trace.json");
const state = {
  profileName: null,
  adapterCalls: 0,
  requestTools: [],
  toolExecutions: [],
  preExecute: 0,
};
function save() {
  try {
    writeFileSync(tracePath, JSON.stringify(state, null, 2) + "\\n");
  } catch {
    // 追踪文件是辅助证据，绝不炸主流程。
  }
}

class ScriptedAdapter extends LlmAdapter {
  #script;
  constructor(script) {
    super();
    this.#script = script;
  }
  resolveModel(provider, model) {
    return Promise.resolve({ provider, id: model, name: model });
  }  async *stream(options) {
    state.adapterCalls += 1;
    state.requestTools.push((options.tools ?? []).map((tool) => tool.name));
    save();
    const chunks = this.#script.shift();
    if (!chunks) throw new Error("ScriptedAdapter: script exhausted");
    for (const chunk of chunks) {
      if (options.signal?.aborted) throw new Error("aborted");
      yield chunk;
    }
  }
}

function textThenToolCallChunks(text, callId, name, args) {
  const argumentsJson = JSON.stringify(args);
  return [
    { type: "block-start", index: 0, blockType: "text" },
    { type: "text-delta", index: 0, text },
    { type: "block-end", index: 0, block: { type: "text", text } },
    { type: "block-start", index: 1, blockType: "tool-call" },
    { type: "tool-call-delta", index: 1, id: ToolCallId(callId), name, argumentsDelta: argumentsJson.slice(0, 5) },
    { type: "tool-call-delta", index: 1, id: ToolCallId(callId), argumentsDelta: argumentsJson.slice(5) },
    { type: "block-end", index: 1, block: { type: "tool-call", id: ToolCallId(callId), name, arguments: argumentsJson } },
    { type: "usage", usage: { inputTokens: 10, outputTokens: 5 } },
    { type: "finish", reason: { kind: "tool-calls" } },
  ];
}

function textChunks(text) {
  return [
    { type: "block-start", index: 0, blockType: "text" },
    { type: "text-delta", index: 0, text },
    { type: "block-end", index: 0, block: { type: "text", text } },
    { type: "usage", usage: { inputTokens: 10, outputTokens: text.length } },
    { type: "finish", reason: { kind: "stop" } },
  ];
}

export class SmokeDriver {
  static inject = ["llm", "tools"];
  constructor(ctx) {
    try {
      state.profileName = ctx.get("profileContext")?.name ?? null;
    } catch {
      state.profileName = null;
    }
    save();
    // fake 模型路由（provider "mock"；zcode-loop 的请求经 dsh llm 路由到达这里）。
    ctx.llm.registerAdapter(["${PROVIDER}"], new ScriptedAdapter([
      textThenToolCallChunks("Calling the echo tool.", "call-smoke-1", "${ECHO_TOOL}", { text: "smoke" }),
      textChunks("${FINAL_TEXT}"),
    ]));
    // dsh 工具插件的注册面：defineTool + ctx.tools.register。
    ctx.tools.register(defineTool({
      name: "${ECHO_TOOL}",
      description: "Echo the given text back (smoke-registered dsh tool).",
      parameters: { text: { type: "string", required: true } },
      output: {
        schema: { type: "object", additionalProperties: true },
        render: (args, value) => [
          { type: "text", text: "Tool says: " + String((value ?? {})?.text ?? "") },
        ],
      },
      execute: async (args) => {
        state.toolExecutions.push({ name: "${ECHO_TOOL}", args });
        save();
        return { text: args.text };
      },
    }));
    // 边界样例 3 判别 probe（真实进程内）：tools/pre-execute 计数。
    ctx.on("tools/pre-execute", async (_exec, next) => {
      state.preExecute += 1;
      save();
      return next();
    });
  }
}

export default SmokeDriver;
`;

/** AC2 重放子进程：npm jsonl 后端读回事件 → npm dsh-session 重放 deriveMessages。 */
const REPLAY_SOURCE = `// generated by scripts/smoke.mjs — durable-log replay (AC2)
import { Context } from "@deepseek-ai/cordis";
import SessionStore, { Session, SessionId } from "@deepseek-ai/dsh-session";
import * as jsonlPersistence from "@deepseek-ai/dsh-session-persistence-jsonl";

const [root, rawId] = process.argv.slice(2);
const ctx = new Context();
await ctx.plugin(SessionStore);
await ctx.plugin(jsonlPersistence, { root, compression: "none" });
const persistence = ctx.get("sessionPersistence");
if (persistence === undefined) throw new Error("replay: sessionPersistence service missing");
const handle = await persistence.open(SessionId(rawId), "read");
try {
  const { events } = await handle.read();
  const session = Session.create(SessionId(rawId), events, handle.header, handle.inheritedEventCount);
  const derived = session.deriveMessages();
  const result = {
    eventCount: events.length,
    types: events.map((event) => event.type),
    roles: derived.map((message) => message.role),
    systemText: derived
      .filter((message) => message.role === "system")
      .map((message) => message.content.map((block) => (block.type === "text" ? block.text : "")).join(""))
      .join("\\n"),
    finalText: (() => {
      const last = derived.at(-1);
      if (last?.role !== "assistant") return null;
      return last.content.filter((block) => block.type === "text").map((block) => block.text).join("");
    })(),
    toolCalls: derived.flatMap((message) =>
      message.role === "assistant"
        ? message.content.filter((block) => block.type === "tool-call").map((block) => ({ id: block.id, name: block.name }))
        : []),
    toolResults: derived
      .filter((message) => message.role === "tool")
      .map((message) => ({
        toolCallId: message.toolCallId,
        text: message.content.filter((block) => block.type === "text").map((block) => block.text).join(""),
        isError: message.isError ?? false,
      })),
  };
  process.stdout.write(JSON.stringify(result));
} finally {
  await handle.close();
}
`;

