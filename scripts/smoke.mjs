function runEsbuildBundle(distEntry, driverSource, outdir) {
  // esbuild 以 devDep 形态解析（devDeps 追加属任务允许的 package.json 改动）。
  const require = createRequire(import.meta.url);
  const esbuild = require("esbuild");
  esbuild.buildSync({
    entryPoints: [
      { in: distEntry, out: "index" },
      { in: driverSource, out: "smoke-driver" },
    ],
    outdir,
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node24",
    sourcemap: false,
    logLevel: "warning",
    // 打进 bundle 的 CJS 依赖（@zcode/core 的传递依赖，如 yaml/typescript）在 ESM
    // 输出里走动态 require 与 __filename/__dirname 探测：banner 统一供给。
    banner: {
      js: [
        "import { createRequire as __createRequire } from 'node:module';",
        "import { fileURLToPath as __fileURLToPath } from 'node:url';",
        "const require = __createRequire(import.meta.url);",
        "const __filename = __fileURLToPath(import.meta.url);",
        "const __dirname = __fileURLToPath(new URL('./', import.meta.url));",
      ].join("\n"),
    },
    external: [
      "@deepseek-ai/cordis",
      "@deepseek-ai/dsh-agent",
      "@deepseek-ai/dsh-llm",
      "@deepseek-ai/dsh-scope",
      "@deepseek-ai/dsh-session",
      "@deepseek-ai/dsh-system-prompt",
      "@deepseek-ai/dsh-tools",
      "@deepseek-ai/schemastery",
    ],
  });
}

/**
 * 把打包产物物化为 profile 内的插件包（`<profile>/node_modules/dsh-plugin-zcode-loop/`）。
 * dsh 的 runtime resolution 对 profile 树内的 bare import：先查
 * `<profile>/node_modules` 的本地候选（本包命中），缺席的 `@deepseek-ai/*`
 * 兜进 installation 作用域（宿主单例 cordis/dsh-*），保证 Service/事件面同源。
 */
function materializePluginPackage(profileDir, bundleDir) {
  const pkgDir = join(profileDir, "node_modules", "dsh-plugin-zcode-loop");
  rmSync(pkgDir, { recursive: true, force: true });
  mkdirSync(pkgDir, { recursive: true });
  for (const file of ["index.js", "smoke-driver.js"]) {
    cpSync(join(bundleDir, file), join(pkgDir, file));
  }
  writeFileSync(
    join(pkgDir, "package.json"),
    JSON.stringify(
      {
        name: "dsh-plugin-zcode-loop",
        version: "0.0.0",
        private: true,
        type: "module",
        exports: {
          ".": "./index.js",
          "./smoke-driver": "./smoke-driver.js",
        },
      },
      null,
      2,
    ) + "\n",
  );
  return pkgDir;
}

/** 镜像 dsh `initProfile` 的 shipped `headless` template（幂等：已存在不覆盖）。 */
function initHeadlessProfile(home) {
  const profileDir = join(home, "profiles", "headless");
  mkdirSync(profileDir, { recursive: true });
  const manifestPath = join(profileDir, "package.json");
  if (!existsSync(manifestPath)) {
    writeFileSync(
      manifestPath,
      JSON.stringify(
        {
          name: "dsh-profile-headless",
          private: true,
          dependencies: {},
          dsh: { profile: { bundles: ["@deepseek-ai/dsh-base", "@deepseek-ai/dsh-headless"] } },
        },
        null,
        2,
      ) + "\n",
    );
  }
  const patchPath = join(profileDir, "cordis.patch.yml");
  if (!existsSync(patchPath)) {
    writeFileSync(
      patchPath,
      `# Your patch layer for this dsh profile, applied after every bundle layer:\n# a top-level YAML array of loader patch entries (id-targeted config\n# overrides, disables, and insert lists; \`!!js\` expressions allowed).\n[]\n`,
    );
  }
  const workspacePath = join(profileDir, "pnpm-workspace.yaml");
  if (!existsSync(workspacePath)) {
    writeFileSync(workspacePath, "packages:\n  - .\n\nnodeLinker: hoisted\nautoInstallPeers: false\n");
  }
  return profileDir;
}

